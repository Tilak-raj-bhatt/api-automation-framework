package com.example.framework.utils;

import com.example.framework.model.ProductRequest;
import com.github.javafaker.Faker;

import java.util.Locale;
import java.util.UUID;

/**
 * Generates unique, realistic test data.
 *
 * <p>Why not hard-code values? Shared suites and parallel CI runs collide on data.
 * A unique title or email per run makes tests repeatable and keeps them
 * independent of execution order.
 */
public final class TestDataFactory {

    private static final Faker FAKER = new Faker(Locale.ENGLISH);

    private TestDataFactory() {
    }

    public static ProductRequest newProduct() {
        return ProductRequest.builder()
                .title("QA " + FAKER.commerce().productName() + " " + uniqueSuffix())
                .description("Payload generated by the automated test suite")
                .category("automation")
                .brand(FAKER.company().name())
                .price(randomPrice())
                .stock(FAKER.number().numberBetween(1, 250))
                .build();
    }

    /** Short, collision-resistant suffix suitable for names and titles. */
    public static String uniqueSuffix() {
        return UUID.randomUUID().toString().substring(0, 8);
    }

    public static String uniqueEmail() {
        return "qa." + UUID.randomUUID().toString().substring(0, 8) + "@example.com";
    }

    private static double randomPrice() {
        double value = FAKER.number().randomDouble(2, 5, 500);
        return Math.round(value * 100.0) / 100.0;
    }
}
